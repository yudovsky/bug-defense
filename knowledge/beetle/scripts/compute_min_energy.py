"""
Minimum energy to penetrate the beetle, per wavelength and power.

For every saved run in knowledge/beetle/raw_arrays/, finds the first time the crater on the beam
mid-plane reaches half penetration (1222 um) and full penetration (2445 um, the bottom of the ventral
shell) while the laser is on, and integrates the delivered power up to that moment. Dual-pulse runs
use their recorded laser schedule. Writes min_energy_to_penetrate.csv and .md next to kpi_cache.json.

    python knowledge/beetle/scripts/compute_min_energy.py
"""

import csv
import glob
import os
import re

import numpy as np

KNOWLEDGE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RAW_DIR = os.path.join(KNOWLEDGE_DIR, "raw_arrays")
FULL_UM = 2445.0
HALF_UM = FULL_UM / 2.0
SINGLE_RE = re.compile(r"^matrix_(\d+)nm_(\d+)w\.npz$")
DUAL_RE = re.compile(r"^matrix_dual_(\d+)nm_(\d+)nm\.npz$")


def delivered_power(d, n):
    """Laser power [W] during each of the first n epochs."""
    if "laser_states" in d.files:
        states = d["laser_states"][:n]
        return np.array([float(re.search(r"@ ([\d.]+) W", str(s)).group(1)) if "@" in str(s) else 0.0
                         for s in states])
    t = d["times"][:n]
    return np.where(t <= 0.2 + 1e-9, float(d["power_w"]), 0.0)


def first_reach(d, depth_um):
    """(time_s, energy_J) when the crater first reaches depth_um with the laser on, else None."""
    t = np.asarray(d["times"], float)
    depth = np.asarray(d["crater_depths_mm"], float) * 1000.0
    p = delivered_power(d, len(t))
    dt = float(d["dt_epoch"]) if "dt_epoch" in d.files else 0.001
    hit = np.where((depth >= depth_um - 1e-6) & (p > 0))[0]
    if hit.size == 0:
        return None
    i = int(hit[0])
    return float(t[i]), float(np.sum(p[: i + 1]) * dt)


def main():
    rows = []
    for path in sorted(glob.glob(os.path.join(RAW_DIR, "matrix_*.npz"))):
        name = os.path.basename(path)
        single, dual = SINGLE_RE.match(name), DUAL_RE.match(name)
        if not (single or dual):
            continue                  # controls (no plume, burst, CW-matched) are not part of the table
        d = np.load(path, allow_pickle=True)
        if single:
            label, power = f"{single.group(1)} nm", f"{single.group(2)} W"
        else:
            label = f"{dual.group(1)} -> {dual.group(2)} nm"
            power = f"{float(d['power_w']):.0f} W x 30 ms, then {float(d['secondary_power_w']):.0f} W"
        half, full = first_reach(d, HALF_UM), first_reach(d, FULL_UM)
        rows.append({
            "run": label, "power": power,
            "half_time_ms": round(half[0] * 1000.0) if half else "", "half_energy_J": round(half[1], 2) if half else "",
            "full_time_ms": round(full[0] * 1000.0) if full else "", "full_energy_J": round(full[1], 2) if full else "",
            "final_depth_um": round(float(np.max(d["crater_depths_mm"])) * 1000.0),
        })
        print(f"{label:>16s} {power:>24s} | half {rows[-1]['half_energy_J']!s:>6} J @ {rows[-1]['half_time_ms']!s:>4} ms"
              f" | full {rows[-1]['full_energy_J']!s:>6} J @ {rows[-1]['full_time_ms']!s:>4} ms | max {rows[-1]['final_depth_um']} um")

    out_csv = os.path.join(KNOWLEDGE_DIR, "min_energy_to_penetrate.csv")
    with open(out_csv, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    out_md = os.path.join(KNOWLEDGE_DIR, "min_energy_to_penetrate.md")
    with open(out_md, "w") as f:
        f.write("# Minimum energy to penetrate\n\n")
        f.write(f"Energy delivered until the mid-plane crater first reaches half ({HALF_UM:.0f} um) or full "
                f"({FULL_UM:.0f} um) penetration with the laser on. 0.5 mm spot, 22.2 deg incidence, plume on, "
                "laser on for up to 200 ms. Generated by `scripts/compute_min_energy.py`.\n\n")
        f.write("| Run | Power | Half: energy (time) | Full: energy (time) | Deepest crater |\n|---|---|---|---|---|\n")
        for r in rows:
            fmt = lambda e, t: f"{e} J ({t} ms)" if e != "" else "not reached"
            f.write(f"| {r['run']} | {r['power']} | {fmt(r['half_energy_J'], r['half_time_ms'])} | "
                    f"{fmt(r['full_energy_J'], r['full_time_ms'])} | {r['final_depth_um']} um |\n")
    print(f"\nWrote {out_csv}\nWrote {out_md}")


if __name__ == "__main__":
    main()
